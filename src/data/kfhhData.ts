export function getAiReply(query: string): string {
  const t = query.toLowerCase();
  if (t.includes('rain') || t.includes('weather')) {
    return 'Rain probability for tomorrow in your area is about 68%, mostly after 4 PM. Plan irrigation and spraying work in the morning.';
  }
  if (t.includes('tomato') || t.includes('price') || t.includes('sell')) {
    return 'Tomato is quoted around ₹2,450 per quintal at Hyderabad mandi today, up 8.4%. Prices have risen for three sessions, so compare two nearby mandis before selling.';
  }
  if (t.includes('demand')) {
    return 'Chilli and basmati rice show increasing demand indicators this month. These are market information signals, not guaranteed returns.';
  }
  if (t.includes('scheme')) {
    return 'Three schemes look relevant for your profile: PM Crop Insurance (closes 30 Sep), Irrigation Subsidy and Kisan Credit Card. Open the Schemes section for documents and official links.';
  }
  if (t.includes('yellow') || t.includes('leaf') || t.includes('leaves')) {
    return 'Yellowing leaves often follow water stress or nutrient deficiency. Check soil moisture, inspect leaf undersides for pests, and share a photo in the AI Crop Doctor for a first assessment.';
  }
  return 'Here is what I can see for your farm today: weather is partly cloudy at 29°C with evening rain likely, paddy health is 87%, and tomato prices are trending up. Ask me about weather, prices, crops or schemes.';
}

